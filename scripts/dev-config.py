#!/usr/bin/env python3
"""Write the developer's server config, runtime/server.dev.toml (git-ignored).

config/server.toml is committed with safe values (loopback binds, no developer tools). Development
setups need the opposite: listening on all interfaces for remote and multi-client tests, the debug
link and position sync for the DLL overlay and drift checks, a movement trace and the known terrain
seeds. This script copies
config/server.toml and switches exactly those keys, keeping every comment, so new keys of the
committed file arrive on the next run.

Usage:
  python3 scripts/dev-config.py            write runtime/server.dev.toml (always regenerated)
  python3 scripts/dev-config.py --if-missing   only when the file does not exist
  python3 scripts/dev-config.py --out FILE     another output path
Then start the server with POE_CONFIG=runtime/server.dev.toml (docs/guides/setup.md).
Local, per-machine changes go into your own copy of the output, not into this script.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "config" / "server.toml"
DEFAULT_OUT = ROOT / "runtime" / "server.dev.toml"

# (section, key) -> new value text
OVERRIDES = {
    ("network.login", "bind"): '"0.0.0.0:20481"',
    ("network.instance", "bind"): '"0.0.0.0:6112"',
    ("dev", "known_seeds"): '"dumps/{version}/terrain/vectors/terrain-vectors.tsv"',
    ("dev", "position_sync"): "true",
    ("dev", "movement_trace"): '"runtime/movement-trace.tsv"',
    ("dev", "debug_link"): "true",
}

HEADER = (
    "# DEVELOPER CONFIG, generated by scripts/dev-config.py from config/server.toml. Git-ignored.\n"
    "# It listens on every interface and turns on the developer tools: never use\n"
    "# it for a server other people can reach. Start with POE_CONFIG=runtime/server.dev.toml.\n\n"
)


def build(text: str) -> str:
    out, section, seen = [], "", set()
    for line in text.splitlines():
        m = re.match(r"\s*\[([^\[\]]+)\]\s*(#.*)?$", line)
        if m:
            section = m.group(1).strip()
        else:
            m = re.match(r"(\s*)([A-Za-z0-9_]+)(\s*=\s*)(.*)$", line)
            if m and (section, m.group(2)) in OVERRIDES:
                key = (section, m.group(2))
                seen.add(key)
                line = f"{m.group(1)}{m.group(2)}{m.group(3)}{OVERRIDES[key]}"
        out.append(line)
    missing = set(OVERRIDES) - seen
    if missing:
        sys.exit(f"dev-config: keys not found in {SRC}: {sorted(missing)}")
    return HEADER + "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--if-missing", action="store_true")
    args = ap.parse_args()
    if args.if_missing and args.out.exists():
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(SRC.read_text()))
    print(f"wrote {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}")


if __name__ == "__main__":
    main()
