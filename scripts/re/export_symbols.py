#!/usr/bin/env python3
"""Build the client DLL's symbol table (client/poe-hook-core/assets/symbols.tsv).

Sources, later ones win:
1. Ghidra's named functions (MSVC runtime and library names), exported with the Ghidra MCP
   `search_functions_enhanced(has_custom_name=true)` into dumps/0.5.5e/ghidra/ghidra_named_functions_p*.json.
2. Our documented addresses: the first column of every table row in
   docs/re/addresses-0.5.5e.md (`| `0x14...` | description | ...`); the description
   becomes the name.

The DLL shows `name+offset` for addresses inside a named function and `FUN_<start>+offset` for
the rest (function bounds from the executable's .pdata table).

Usage: scripts/re/export_symbols.py
"""

import glob
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "client/poe-hook-core/assets/symbols.tsv"


def clean(text: str) -> str:
    text = re.sub(r"`", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:80]


def main():
    names = {}
    for path in sorted(glob.glob(str(ROOT / "dumps/0.5.5e/ghidra/ghidra_named_functions_p*.json"))):
        outer = json.loads(Path(path).read_text())
        inner = json.loads(outer["result"]) if isinstance(outer.get("result"), str) else outer
        for f in inner.get("results", []):
            names[int(f["address"], 16)] = f["name"]
    doc = (ROOT / "docs/re/addresses-0.5.5e.md").read_text()
    for line in doc.splitlines():
        m = re.match(r"^\|\s*`(0x14[0-9a-fA-F]{7})`\s*\|\s*([^|]+)\|", line)
        if m:
            names[int(m.group(1), 16)] = clean(m.group(2))
    OUT.write_text(
        "# address\tname (generated by scripts/re/export_symbols.py)\n"
        + "".join(f"{a:x}\t{n}\n" for a, n in sorted(names.items()))
    )
    print(f"{len(names)} symbols -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
