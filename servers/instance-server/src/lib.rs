//! Instance server: hosts areas. The login server hands clients over with a ticket;
//! the instance server validates it, sends the area and runs the simulation.
//!
//! Connection opening (Documentation/protocol/instance.md):
//! 1. client `Hello` (plaintext) carrying the hand-off ticket,
//! 2. server `EnableEncryption` (plaintext), then both directions switch to Salsa20 with the
//!    ticket's key material,
//! 3. server `AreaInfo` (area + seed): the client generates the terrain and loads the area.

use std::sync::Arc;

use poe_cluster::{Ticket, TicketRegistry};
use poe_config::Config;
use poe_data::{GameData, views::WorldArea};
use poe_net::{Connection, DecodeError, KeyMaterial, hexdump::hexdump};
use poe_proto::{
    Message, Protocol,
    instance::{AreaInfo, EnableEncryption, Hello, InitialState, LocalPlayers, TerrainHashes},
};
use rand::RngCore;
use tokio::net::{TcpListener, TcpStream};
use tracing::{Instrument, info, warn};

/// State shared by all instance connections.
pub struct InstanceServer {
    pub config: Arc<Config>,
    pub protocol: Arc<Protocol>,
    pub tickets: Arc<dyn TicketRegistry>,
    pub data: Arc<GameData>,
}

impl InstanceServer {
    pub async fn run(self: Arc<Self>) -> anyhow::Result<()> {
        let listener = TcpListener::bind(self.config.instance.bind).await?;
        info!(addr = %self.config.instance.bind, "instance server listening");
        loop {
            let (stream, peer) = listener.accept().await?;
            let span = tracing::info_span!("instance", %peer);
            let server = self.clone();
            tokio::spawn(
                async move {
                    if let Err(e) = server.handle(stream).await {
                        warn!("connection error: {e:#}");
                    }
                }
                .instrument(span),
            );
        }
    }

    async fn handle(&self, stream: TcpStream) -> anyhow::Result<()> {
        let mut conn = Connection::new(stream)?;
        info!("client connected");
        let hello_op = self.protocol.instance.id(Hello::DIRECTION, Hello::NAME)?;
        let Some(hello) = conn
            .decode(|r| {
                let at = r.position();
                if r.u16()? != hello_op {
                    return Err(DecodeError::Invalid {
                        offset: at,
                        what: "expected Hello",
                    });
                }
                Hello::decode(r)
            })
            .await?
        else {
            return Ok(());
        };
        let Some(ticket) = self.tickets.redeem(hello.ticket) else {
            warn!(
                ticket = format_args!("{:#010x}", hello.ticket),
                "unknown or expired ticket"
            );
            return Ok(());
        };
        info!(
            ticket = format_args!("{:#010x}", ticket.id),
            account = ticket.account_id,
            character = ticket.character_id,
            area = %ticket.area,
            "ticket redeemed"
        );

        conn.send(
            &self
                .protocol
                .instance
                .encode(&EnableEncryption::default())?,
        )
        .await?;
        let keys = KeyMaterial(ticket.keys);
        conn.set_ciphers(
            Box::new(keys.client_to_server()),
            Box::new(keys.server_to_client()),
        );

        self.send_area(&mut conn, &ticket).await?;

        let hashes_op = self
            .protocol
            .instance
            .id(TerrainHashes::DIRECTION, TerrainHashes::NAME)?;
        if let Some(h) = conn
            .decode(|r| {
                let at = r.position();
                if r.u16()? != hashes_op {
                    return Err(DecodeError::Invalid {
                        offset: at,
                        what: "expected TerrainHashes",
                    });
                }
                TerrainHashes::decode(r)
            })
            .await?
        {
            info!(
                unk = h.unk,
                hash_a = format_args!("{:#010x}", h.hash_a),
                hash_b = format_args!("{:#010x}", h.hash_b),
                "terrain generated by client"
            );
        }

        // RE experiment: which post-area messages to send, from POE_EXPERIMENT (comma list of
        // "players", "initial"); default: none.
        let experiment = std::env::var("POE_EXPERIMENT").unwrap_or_default();
        if experiment.split(',').any(|e| e == "players") {
            let players = LocalPlayers {
                unk: 0,
                players: vec![(0, ticket.character_name.clone())],
            };
            conn.send(&self.protocol.instance.encode(&players)?).await?;
            info!("sent LocalPlayers");
        }
        if experiment.split(',').any(|e| e == "spawn") {
            // 0x24: local player 0 controls entity 1; 0x2f7 adds entity 1 (type key 0, empty
            // blob); then tick markers so the simulation frame is applied.
            let mut w = poe_net::Writer::new();
            w.u16(0x24).u8(0).u8(0).u32(1);
            w.u16(0x2f7).u32(1).u32(0).u8(0).u16(0).u32(0).varuint(0);
            for _ in 0..3 {
                w.u16(0x2f4);
            }
            conn.send(w.as_slice()).await?;
            info!("sent spawn experiment");
        }
        if experiment.split(',').any(|e| e == "entity") {
            // Empty 0x2f7 (simulation header + u32 + empty blob) to trace its consumer.
            let mut w = poe_net::Writer::new();
            w.u16(0x2f7).u32(0).u32(0).u8(0).u16(0).u32(0).varuint(0);
            conn.send(w.as_slice()).await?;
            info!("sent empty 0x2f7");
        }
        if experiment.split(',').any(|e| e == "initial") {
            conn.send(&self.protocol.instance.encode(&InitialState::default())?)
                .await?;
            info!("sent InitialState");
        }

        // Not decoded yet: log the client's decrypted messages.
        loop {
            if conn.buffer().is_empty() && conn.read_more().await? == 0 {
                info!("client disconnected");
                return Ok(());
            }
            info!(
                len = conn.buffer().len(),
                "received\n{}",
                hexdump(conn.buffer())
            );
            let n = conn.buffer().len();
            conn.consume(n);
        }
    }

    async fn send_area(&self, conn: &mut Connection, ticket: &Ticket) -> anyhow::Result<()> {
        let Some(area) = WorldArea::find(&self.data, &ticket.area)? else {
            anyhow::bail!("ticket area {} not in game data", ticket.area);
        };
        let (instance_id, seed) = {
            let mut rng = rand::rng();
            (rng.next_u32(), rng.next_u32())
        };
        let msg = AreaInfo {
            instance_id,
            area_hash: area.hash16,
            text_38: String::new(),
            seed,
            ..Default::default()
        };
        info!(area = %area.id, seed = msg.seed, instance = msg.instance_id, "sending area");
        conn.send(&self.protocol.instance.encode(&msg)?).await?;
        Ok(())
    }
}
